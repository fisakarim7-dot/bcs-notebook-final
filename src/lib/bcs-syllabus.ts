/** Official BCS syllabus skeleton — seeded once, never overwrites user status. */

export interface SyllabusSeed {
  paper: "prelim" | "written";
  subject: string;
  topic: string;
  marks: number;
  order: number;
}

const P = (
  subject: string,
  topics: string[],
  marks: number,
  start: number
): SyllabusSeed[] =>
  topics.map((topic, i) => ({
    paper: "prelim" as const,
    subject,
    topic,
    marks: i === 0 ? marks : 0,
    order: start + i,
  }));

const W = (
  subject: string,
  topics: string[],
  marks: number,
  start: number
): SyllabusSeed[] =>
  topics.map((topic, i) => ({
    paper: "written" as const,
    subject,
    topic,
    marks: i === 0 ? marks : 0,
    order: start + i,
  }));

